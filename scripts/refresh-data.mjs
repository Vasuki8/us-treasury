import { writeFile,rename } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { snapshot as previous } from '../src/official-snapshot.js';
import { collectTreasury } from './sources/treasury.mjs';
import { collectBls } from './sources/bls.mjs';
import { collectBea } from './sources/bea.mjs';
import { refreshSnapshot } from './sources/refresh.mjs';
import { assertCommercialData } from './data-policy.mjs';

const all={treasury:collectTreasury,bls:collectBls,bea:collectBea};
const selection=process.argv.find(arg=>arg.startsWith('--sources='))?.split('=')[1]?.split(',')||Object.keys(all);
if(selection.some(id=>!Object.hasOwn(all,id)))throw new Error('Sources must be treasury,bls,bea');
const collectors=Object.fromEntries(selection.map(id=>[id,async options=>{
  console.log(`Retrieving ${id.toUpperCase()} official data…`);
  return all[id](options);
}]));
const snapshot=await refreshSnapshot({previous,collectors});
assertCommercialData(snapshot);
const destination=fileURLToPath(new URL('../src/official-snapshot.js',import.meta.url));
const temporary=path.join(path.dirname(destination),'.official-snapshot.tmp');
await writeFile(temporary,`// Generated by npm run data:refresh from official agency responses. Do not edit observations by hand.\nexport const snapshot = ${JSON.stringify(snapshot,null,2)};\n`);
await rename(temporary,destination);
for(const id of selection) {
  const source=snapshot.sources[id];
  if(source.status==='ok')console.log(`${id.toUpperCase()}: refreshed ${Object.keys(source.series).length} series at ${source.fetchedAt}`);
  else console.error(`${id.toUpperCase()}: ${source.error}${source.fetchedAt?`; retained snapshot from ${source.fetchedAt}`:'; no observations available'}`);
}
if(selection.some(id=>snapshot.sources[id].status!=='ok'))process.exitCode=1;
